import { AppRegistryNotReady, ImproperlyConfigured } from './errors'

export type CommandClassLike = new () => {
  handle(args: Record<string, unknown>, io: any): Promise<void | number>
}

/** Django's AppConfig. Subclass it in `src/<app>/app.ts`. */
export abstract class AppConfig {
  abstract name: string
  label?: string
  verboseName?: string
  /** Directory of the app (`import.meta.dirname`). Only used by the CLI (migrations). */
  path?: string
  /** `import * as models from './models'` — every Model class found is registered to this app. */
  models?: Record<string, unknown> | unknown[]
  /** `import * as migrations from './migrations'` (index generated by makemigrations). */
  migrations?: Record<string, unknown>
  /** `import * as admin from './admin'` — importing the module registers ModelAdmins. */
  admin?: unknown
  /** Agents, signals or any other module the app wants loaded at startup. */
  modules?: Record<string, unknown>
  commands?: Record<string, CommandClassLike>
  ready?(): void | Promise<void>

  get appLabel(): string {
    return this.label ?? this.name.split(/[./]/).pop()!
  }

  get displayName(): string {
    return this.verboseName ?? this.appLabel.charAt(0).toUpperCase() + this.appLabel.slice(1)
  }
}

export type AppConfigClass = new () => AppConfig

type PopulateHook = (registry: AppRegistry) => void | Promise<void>

export class AppRegistry {
  private configs = new Map<string, AppConfig>()
  private models = new Map<string, Map<string, unknown>>() // appLabel → lower model name → model
  private hooks: PopulateHook[] = []
  private populating: Promise<void> | null = null
  private _ready = false
  private installedKey: unknown = null

  get ready(): boolean {
    return this._ready
  }

  /** Packages (the ORM) register hooks that run after configs are created and before `ready()`. */
  onPopulate(hook: PopulateHook): void {
    this.hooks.push(hook)
  }

  /** Idempotent for the same INSTALLED_APPS array. Re-populates if a different list is passed (tests). */
  populate(installed: Array<AppConfigClass | AppConfig>): Promise<void> {
    if (this.populating && sameApps(this.installedKey, installed)) return this.populating
    if (this.installedKey !== null && !sameApps(this.installedKey, installed)) this.reset()
    this.installedKey = installed
    this.populating = this.doPopulate(installed).catch((err) => {
      this.populating = null
      this.installedKey = null
      throw err
    })
    return this.populating
  }

  private async doPopulate(installed: Array<AppConfigClass | AppConfig>): Promise<void> {
    for (const entry of installed) {
      const config = typeof entry === 'function' ? new (entry as AppConfigClass)() : entry
      if (!(config instanceof AppConfig) && typeof (config as any)?.name !== 'string') {
        throw new ImproperlyConfigured(`INSTALLED_APPS entry ${String(entry)} is not an AppConfig.`)
      }
      const label = (config as AppConfig).appLabel
      if (this.configs.has(label)) {
        throw new ImproperlyConfigured(`Application labels aren't unique, duplicates: ${label}`)
      }
      this.configs.set(label, config as AppConfig)
      if (!this.models.has(label)) this.models.set(label, new Map())
    }
    for (const hook of this.hooks) await hook(this)
    for (const config of this.configs.values()) await config.ready?.()
    this._ready = true
  }

  /** Clear everything (tests). Hooks stay registered. */
  reset(): void {
    this.configs.clear()
    this.models.clear()
    this.populating = null
    this.installedKey = null
    this._ready = false
  }

  getAppConfigs(): AppConfig[] {
    return [...this.configs.values()]
  }

  getAppConfig(label: string): AppConfig {
    const c = this.configs.get(label)
    if (!c) throw new LookupError(`No installed app with label '${label}'.`)
    return c
  }

  isInstalled(label: string): boolean {
    return this.configs.has(label)
  }

  registerModel(appLabel: string, model: unknown): void {
    const name = modelName(model)
    let bucket = this.models.get(appLabel)
    if (!bucket) {
      bucket = new Map()
      this.models.set(appLabel, bucket)
    }
    const existing = bucket.get(name)
    if (existing && existing !== model) {
      throw new ImproperlyConfigured(`Conflicting '${name}' models in application '${appLabel}'.`)
    }
    bucket.set(name, model)
  }

  getModels(appLabel?: string): unknown[] {
    if (appLabel) return [...(this.models.get(appLabel)?.values() ?? [])]
    return [...this.models.values()].flatMap((m) => [...m.values()])
  }

  /** `getModel('blog.Post')` or `getModel('blog', 'post')` (case-insensitive model name). */
  getModel(appLabelOrDotted: string, name?: string): unknown {
    let app = appLabelOrDotted
    let model = name
    if (model === undefined) {
      const idx = appLabelOrDotted.lastIndexOf('.')
      if (idx < 0)
        throw new LookupError(`Model label must be 'app_label.ModelName', got '${appLabelOrDotted}'.`)
      app = appLabelOrDotted.slice(0, idx)
      model = appLabelOrDotted.slice(idx + 1)
    }
    const found = this.models.get(app)?.get(model.toLowerCase())
    if (!found) {
      if (!this._ready && !this.populating) throw new AppRegistryNotReady("Models aren't loaded yet.")
      throw new LookupError(`App '${app}' doesn't have a '${model}' model.`)
    }
    return found
  }
}

export class LookupError extends ImproperlyConfigured {}

/** Same INSTALLED_APPS (identical array, or same entries in the same order — settings resolved per env). */
function sameApps(a: unknown, b: unknown[]): boolean {
  if (a === b) return true
  if (!Array.isArray(a) || a.length !== b.length) return false
  return a.every((x, i) => x === b[i])
}

function modelName(model: unknown): string {
  const m = model as any
  return String(m?._meta?.modelName ?? m?.name ?? '').toLowerCase()
}

// Singleton shared across duplicate module instances.
const KEY = Symbol.for('ghuri.core.apps')
export const apps: AppRegistry = ((globalThis as any)[KEY] ??= new AppRegistry())

export function ensureAppsReady(): void {
  if (!apps.ready) throw new AppRegistryNotReady("Apps aren't loaded yet.")
}
